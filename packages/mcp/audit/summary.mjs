#!/usr/bin/env node
/**
 * Renders the "Latest audit run" block of AUDIT.md from audit-results.json and
 * the benchmark contract, so the human report can never drift from the
 * machine-readable evidence.
 *
 *   node audit/summary.mjs          rewrite the block in AUDIT.md
 *   node audit/summary.mjs --check  exit 1 when the block is stale
 *
 * `pnpm audit:evidence` runs the strict full audit and then this script;
 * `pnpm release` refuses to publish when the block is stale.
 */
import { readFileSync, writeFileSync } from "node:fs"
import { dirname, resolve } from "node:path"
import { fileURLToPath } from "node:url"
import { REAL_CLI_CLIENTS_CHECK_ID } from "./gates.mjs"

const pkgRoot = resolve(dirname(fileURLToPath(import.meta.url)), "..")
export const AUDIT_FILES = {
  report: resolve(pkgRoot, "audit-results.json"),
  summary: resolve(pkgRoot, "AUDIT.md"),
  contract: resolve(pkgRoot, "../../docs/benchmark-release.json"),
}

export const SUMMARY_START =
  "<!-- audit-results:start: generated by `node packages/mcp/audit/summary.mjs` from audit-results.json; do not edit by hand -->"
export const SUMMARY_END = "<!-- audit-results:end -->"

const pct = (x) => `${(x * 100).toFixed(1)}%`
const ms = (x) => `${x} ms`
const cell = (text) => String(text).replaceAll("|", "\\|").replaceAll("\n", " ")

/**
 * The contract's release label and standalone numbers only describe the
 * audited run when the contract pins the same model revision.
 */
export function contractMatchesReport(report, contract) {
  return contract.artifact?.revision === report.model?.revision
}

/** The generated Markdown block, start and end markers included. */
export function renderAuditSummary(report, contract) {
  if (!contractMatchesReport(report, contract)) {
    throw new Error(
      `audit-results.json audited model ${report.model?.revision}, but docs/benchmark-release.json pins ${contract.artifact?.revision}: rerun \`pnpm audit:evidence\``,
    )
  }
  const suites = Object.fromEntries(report.suites.map((s) => [s.suite, s]))
  const bench = suites.benchmark?.metrics ?? {}
  const gates = report.releaseGates
  const env = report.environment
  const standalone = contract.metrics
  const lines = [
    SUMMARY_START,
    "",
    "## Latest audit run",
    "",
    `- **Run:** ${report.timestamp.slice(0, 10)} (\`${report.lane}\` lane, ${gates.release ? "`--release` gate: every gate must PASS" : "non-release run"}), commit \`${report.commitSha.slice(0, 12)}\``,
    `- **Package:** \`${report.packageName}@${report.packageVersion}\``,
    `- **Model:** \`${report.model.id}\` (${contract.release}, pinned revision \`${report.model.revision}\`)`,
    `- **Test machine:** ${env.cpu} (${env.cpuCount} cores), ${Math.round(env.ramBytes / 2 ** 30)} GiB RAM, \`${env.platform}/${env.arch}\`, Node \`${env.node}\`${env.ci ? ", CI" : ""}`,
    `- **Checks:** PASS ${report.totals.pass}, FAIL ${report.totals.fail}, BLOCKED ${report.totals.blocked}, NOT TESTED ${report.totals.notTested}`,
    `- **Release gates:** ${gates.summary.pass}/${gates.summary.total} PASS, verdict **${gates.verdict}**`,
    "",
    "| Gate | Category | Status | Evidence |",
    "| --- | --- | --- | --- |",
    ...gates.gates.map(
      (g) => `| \`${g.id}\` | ${g.category} | **${g.status}** | ${cell(g.detail)} |`,
    ),
    "",
    "**Checks not tested in this run:**",
    "",
  ]
  const notTested = report.suites.flatMap((s) =>
    s.checks.filter((c) => c.status !== "PASS").map((c) => ({ suite: s.suite, ...c })),
  )
  if (notTested.length === 0) lines.push("- none")
  for (const c of notTested) {
    lines.push(`- \`${c.suite}/${c.id}\` (${c.status}): ${cell(c.detail || c.description)}`)
  }

  const realCli = suites.clients?.checks.find((c) => c.id === REAL_CLI_CLIENTS_CHECK_ID)
  if (realCli?.status === "PASS") {
    const inventory = Object.values(suites.clients.metrics?.clientInventory ?? {})
      .filter((v) => v.startsWith("INSTALLED ("))
      .map((v) => v.slice("INSTALLED (".length, -1))
    lines.push(
      "",
      `**Real clients over the installed tarball:** ${inventory.join(", ")}: ${cell(realCli.detail)}`,
    )
  }

  lines.push(
    "",
    `### Production-pipeline quality (${bench.corpusDocuments} unseen documents, \`${bench.mode}\` mode)`,
    "",
    `Measured through the live MCP server and HTTP proxy. The standalone column is the ${contract.release} release contract (\`docs/benchmark-release.json\`, reported in \`docs/BENCHMARKS.md\`) on its own, larger corpora, so the two columns are not the same test set.`,
    "",
    `| Metric | Pipeline (\`@maskera/mcp@${report.packageVersion}\`) | Standalone ${contract.release} |`,
    "| --- | ---: | ---: |",
    `| Structured PII recall | ${pct(bench.structuredRecall)} | ${standalone.structuredRegression.hitRatePct}% (structured regression) |`,
    `| Overall entity recall | ${pct(bench.overallRecall)} | ${standalone.curated.recallPct}% (curated) |`,
    `| Span precision | ${pct(bench.overallPrecision)} | ${standalone.curated.precisionPct}% (curated) |`,
    `| Span F1 | ${pct(bench.overallF1)} | ${standalone.curated.spanF1Pct}% (curated) |`,
    `| Document leakage rate | ${pct(bench.documentLeakageRate)} | ${standalone.curated.leaks} leaks / ${standalone.curated.documents} documents (curated) |`,
    `| Protected non-PII retention | ${pct(bench.nonPiiRetention)} | not measured |`,
    `| Round-trip restoration | ${pct(bench.roundtripAccuracy)} | not measured |`,
    "",
    "| Label | Gold | Recall | Precision | F1 |",
    "| --- | ---: | ---: | ---: | ---: |",
    ...Object.entries(bench.perLabel ?? {})
      .filter(([, m]) => m.gold > 0)
      .map(
        ([label, m]) =>
          `| \`${label}\` | ${m.gold} | ${pct(m.recall)} | ${pct(m.precision)} | ${pct(m.f1)} |`,
      ),
    "",
    "### Performance, concurrency and soak",
    "",
    "One run on the machine above; latencies move with machine load, so compare against the gate ceilings in RELEASE_GATES.md, not run to run.",
    "",
    `- **CLI cold start (\`--version\`):** ${ms(bench.cliColdStartMs)}`,
    `- **Local ONNX model load:** ${ms(bench.modelLoadMs)}`,
    `- **ONNX inference (cache disabled):** p50 ${ms(bench.inferenceP50Ms)}, p95 ${ms(bench.inferenceP95Ms)}, p99 ${ms(bench.inferenceP99Ms)}`,
    `- **HTTP proxy round trip:** p50 ${ms(bench.proxyP50Ms)}, p95 ${ms(bench.proxyP95Ms)}, p99 ${ms(bench.proxyP99Ms)} (median proxy overhead ${ms(bench.proxyOverheadP50Ms)})`,
    `- **StreamingRestorer:** 10,000 chunks in ${ms(bench.streaming10kMs)}`,
    `- **Concurrent burst:** ${bench.concurrentThroughputRps} req/s`,
    `- **Soak:** ${bench.soakOps} operations, heap delta ${bench.soakHeapGrowthMb} MB, \`SessionVault\` bounded: ${bench.soakVaultSessionsBounded ? "yes" : "no"}`,
  )

  const tarballs = suites.package?.metrics?.tarballs ?? {}
  if (Object.keys(tarballs).length > 0) {
    lines.push(
      "",
      "### Packed tarballs",
      "",
      "| Package | Bytes | SHA-256 |",
      "| --- | ---: | --- |",
      ...Object.entries(tarballs).map(
        ([name, t]) => `| \`${name}\` | ${t.bytes} | \`${t.sha256}\` |`,
      ),
    )
  }

  lines.push("", SUMMARY_END)
  return lines.join("\n")
}

/** The current generated block in AUDIT.md, or null when the markers are missing. */
export function extractSummaryBlock(markdown) {
  const start = markdown.indexOf(SUMMARY_START)
  const end = markdown.indexOf(SUMMARY_END)
  if (start < 0 || end < start) return null
  return markdown.slice(start, end + SUMMARY_END.length)
}

export function replaceSummaryBlock(markdown, block) {
  const current = extractSummaryBlock(markdown)
  if (current === null) {
    throw new Error(`AUDIT.md has no ${SUMMARY_START} ... ${SUMMARY_END} block`)
  }
  return markdown.replace(current, () => block)
}

const readJson = (path) => JSON.parse(readFileSync(path, "utf8"))

/** Rewrites AUDIT.md from the evidence on disk; returns true when it changed. */
export function writeAuditSummary() {
  const markdown = readFileSync(AUDIT_FILES.summary, "utf8")
  const block = renderAuditSummary(readJson(AUDIT_FILES.report), readJson(AUDIT_FILES.contract))
  const next = replaceSummaryBlock(markdown, block)
  if (next !== markdown) writeFileSync(AUDIT_FILES.summary, next)
  return next !== markdown
}

/** True when AUDIT.md's block matches what the evidence on disk renders. */
export function auditSummaryIsCurrent(markdown, report, contract) {
  return (
    contractMatchesReport(report, contract) &&
    extractSummaryBlock(markdown) === renderAuditSummary(report, contract)
  )
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  if (process.argv.includes("--check")) {
    const ok = auditSummaryIsCurrent(
      readFileSync(AUDIT_FILES.summary, "utf8"),
      readJson(AUDIT_FILES.report),
      readJson(AUDIT_FILES.contract),
    )
    if (!ok) {
      console.error("AUDIT.md is stale: run `node packages/mcp/audit/summary.mjs`")
      process.exit(1)
    }
  } else {
    console.log(writeAuditSummary() ? "AUDIT.md updated" : "AUDIT.md already current")
  }
}
