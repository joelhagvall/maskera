import { readdirSync, readFileSync } from "node:fs"
import { resolve } from "node:path"
import { describe, expect, it } from "vitest"
import {
  getViewMeta,
  MAX_TITLE_LENGTH,
  ogImagePath,
  renderRouteHtml,
  routeHtmlViews,
  TITLE_SUFFIX,
  viewMeta,
  viewPaths,
  viewUrl,
} from "../src/meta"
import type { View } from "../src/paths"

/**
 * The static sub-page shells are generated from viewMeta, the same data
 * applyViewMeta writes during SPA navigation. These tests pin the contract:
 * whatever a crawler sees on a direct landing is what the client would have
 * set, correctly escaped.
 */
describe("renderRouteHtml", () => {
  for (const view of routeHtmlViews) {
    it(`${viewPaths[view]} carries its viewMeta title, description and canonical`, () => {
      const html = renderRouteHtml(view)
      const url = viewUrl(view)
      expect(html).toContain(`<link rel="canonical" href="${url}" />`)
      expect(html).toContain(`<meta property="og:url" content="${url}" />`)
      // & in "integritet & transparens" must be escaped in attributes/title
      const title = viewMeta[view].title.replace(/&/g, "&amp;")
      expect(html).toContain(`<title>${title}</title>`)
      expect(html).toContain(`<meta property="og:title" content="${title}" />`)
      expect(html).toContain(viewMeta[view].description.replace(/&/g, "&amp;"))
      expect(html).toContain('<script type="module" src="/src/main.tsx"></script>')
    })
  }

  it("escapes the ampersand in the transparency title", () => {
    expect(renderRouteHtml("transparency")).toContain(
      "<title>Integritet &amp; transparens · Maskera</title>",
    )
  })

  it("keeps every page title short, capitalized and suffixed once", () => {
    for (const locale of ["sv", "en"] as const) {
      for (const [view, meta] of Object.entries(getViewMeta(locale))) {
        const where = `${locale}/${view}: ${meta.title}`
        expect(meta.title.length, where).toBeLessThanOrEqual(MAX_TITLE_LENGTH)
        expect(meta.title.endsWith(TITLE_SUFFIX), where).toBe(true)
        expect(meta.title.split(TITLE_SUFFIX).length, where).toBe(2)
        expect(meta.title, where).toMatch(/^[@A-ZÅÄÖ]/)
      }
    }
  })

  it("gives every page its own committed 1200x630 preview card and nothing stale", () => {
    const publicDir = resolve(__dirname, "..", "public")
    const expected = new Set<string>()
    for (const locale of ["sv", "en"] as const) {
      for (const [view, meta] of Object.entries(getViewMeta(locale))) {
        const path = ogImagePath(view as View, locale)
        expect(meta.ogImage).toBe(`https://maskera.dev${path}`)
        const png = readFileSync(resolve(publicDir, path.slice(1)))
        // PNG IHDR: width and height as big-endian uint32 at bytes 16 and 20
        expect([png.readUInt32BE(16), png.readUInt32BE(20)], path).toEqual([1200, 630])
        expected.add(path)
      }
    }
    const committed = readdirSync(resolve(publicDir, "og"), { recursive: true })
      .map(String)
      .filter((file) => file.endsWith(".png"))
      .map((file) => `/og/${file}`)
    const stale = committed.filter((path) => !expected.has(path))
    expect(stale, "run pnpm --filter @maskera/demo render:social").toEqual([])
  })

  it("has rendered every preview card from the current titles, descriptions and sample", async () => {
    const { CARDS_LOCK, cardHash, socialCards } = await import("../scripts/social-cards.mjs")
    const modules = {
      meta: await import("../src/meta"),
      scenes: await import("../src/heroScenes"),
      labels: await import("../src/labels"),
      i18n: await import("../src/i18n"),
    }
    const lock = JSON.parse(readFileSync(CARDS_LOCK, "utf8"))
    const current = Object.fromEntries(
      socialCards(modules).map((card: { file: string; html: string }) => [
        card.file,
        cardHash(card.html),
      ]),
    )
    expect(current, "run pnpm --filter @maskera/demo render:social").toEqual(lock)
  })

  it("keeps the hand-written home shell's meta tags equal to the rendered home meta", () => {
    // index.html is the one shell not generated by renderRouteHtml; its
    // og/twitter copies drifted from the i18n source before (2026-11-27).
    const metas = (html: string) =>
      Object.fromEntries(
        [
          ...html
            .replace(/\s+/g, " ")
            .matchAll(/<meta (?:property|name)="([^"]+)" content="([^"]*)"/g),
        ].map((m) => [m[1], m[2]]),
      )
    const shell = readFileSync(resolve(__dirname, "..", "index.html"), "utf8")
    const rendered = renderRouteHtml("demo", "sv")
    const expected = metas(rendered)
    for (const [key, value] of Object.entries(metas(shell))) {
      if (key in expected) expect(value, key).toBe(expected[key])
    }
    expect(shell).toContain(rendered.match(/<title>[^<]*<\/title>/)?.[0])
  })

  it("embeds valid JSON-LD", () => {
    for (const view of routeHtmlViews) {
      const html = renderRouteHtml(view)
      const match = html.match(/<script type="application\/ld\+json">\s*([\s\S]*?)\s*<\/script>/)
      expect(match).not.toBeNull()
      const data = JSON.parse(match?.[1] ?? "")
      expect(data.url).toBe(viewUrl(view))
    }
  })

  it("names the operator's contact point in the home page JSON-LD", () => {
    const html = renderRouteHtml("demo", "en")
    const match = html.match(/<script type="application\/ld\+json">\s*([\s\S]*?)\s*<\/script>/)
    const data = JSON.parse(match?.[1] ?? "")
    expect(data.publisher["@type"]).toBe("Organization")
    expect(data.publisher.address).toMatchObject({ "@type": "PostalAddress", addressCountry: "SE" })
    expect(data.publisher.contactPoint[0]).toMatchObject({
      "@type": "ContactPoint",
      email: "hej@maskera.dev",
    })
  })

  it("marks the about page as AboutPage and ContactPage with the operator as main entity", () => {
    for (const locale of ["sv", "en"] as const) {
      const html = renderRouteHtml("about", locale)
      const match = html.match(/<script type="application\/ld\+json">\s*([\s\S]*?)\s*<\/script>/)
      const data = JSON.parse(match?.[1] ?? "")
      expect(data["@type"]).toEqual(["AboutPage", "ContactPage"])
      expect(data.mainEntity.name).toBe("Hägvall Labs AB")
      expect(data.mainEntity.contactPoint[0].email).toBe("hej@maskera.dev")
    }
  })

  it("exposes structured product offers on the services page in both locales", () => {
    for (const locale of ["sv", "en"] as const) {
      const html = renderRouteHtml("services", locale)
      const match = html.match(/<script type="application\/ld\+json">\s*([\s\S]*?)\s*<\/script>/)
      const data = JSON.parse(match?.[1] ?? "")
      expect(data.mainEntity["@type"]).toBe("ItemList")
      expect(data.mainEntity.itemListElement).toHaveLength(3)
      const [ext, agents, sdk] = data.mainEntity.itemListElement.map(
        (entry: { item: Record<string, unknown> }) => entry.item,
      )
      expect(ext.offers).toHaveLength(3)
      expect(agents.sameAs).toBe("https://www.npmjs.com/package/@maskera/mcp")
      expect(sdk.sameAs).toBe("https://www.npmjs.com/package/maskera")
    }
  })

  it("advertises the Markdown alternate on every shell", () => {
    for (const view of routeHtmlViews) {
      for (const locale of ["sv", "en"] as const) {
        const html = renderRouteHtml(view, locale)
        expect(html).toContain(
          `<link rel="alternate" type="text/markdown" href="${new URL(viewUrl(view, locale)).pathname}.md" />`,
        )
      }
    }
  })

  it("only the docs pages preload the mono font their code needs", () => {
    expect(renderRouteHtml("docsSdk")).toContain("geist-mono-latin.woff2")
    expect(renderRouteHtml("transparency")).not.toContain("geist-mono-latin.woff2")
    expect(renderRouteHtml("testdata")).not.toContain("geist-mono-latin.woff2")
    expect(renderRouteHtml("privacy")).not.toContain("geist-mono-latin.woff2")
    expect(renderRouteHtml("services")).not.toContain("geist-mono-latin.woff2")
    expect(renderRouteHtml("accuracy")).not.toContain("geist-mono-latin.woff2")
    expect(renderRouteHtml("security")).not.toContain("geist-mono-latin.woff2")
  })

  it("renders English shells with matching paths, metadata and locale alternates", () => {
    const html = renderRouteHtml("docsSdk", "en")
    const meta = getViewMeta("en").docsSdk

    expect(html).toContain('<html lang="en">')
    expect(html).toContain(`<title>${meta.title}</title>`)
    expect(html).toContain('<link rel="canonical" href="https://maskera.dev/en/docs/sdk" />')
    expect(html).toContain(
      '<link rel="alternate" hreflang="sv" href="https://maskera.dev/docs/sdk" />',
    )
    expect(html).toContain(
      '<link rel="alternate" hreflang="en" href="https://maskera.dev/en/docs/sdk" />',
    )
  })
})
